package handler

import (
	"regexp"

	"github.com/microcosm-cc/bluemonday"
)

// articleSanitizationPolicy keeps article HTML safe while allowing the shared
// coloured-circle treatment used when editorial content refers to a number pair.
func articleSanitizationPolicy() *bluemonday.Policy {
	policy := bluemonday.UGCPolicy()
	// Quill uses classes for list, alignment, colour, and inline emphasis
	// markup. In particular, a selected bold phrase can be serialised as
	// <strong class="ql-color-gold">…</strong>. Keep those presentation-only
	// classes so colour is not lost after the article is saved.
	policy.AllowAttrs("class").OnElements("span", "strong", "b", "em", "i", "u", "s", "strike", "p", "h1", "h2", "h3", "ol", "ul", "li", "blockquote")
	policy.AllowAttrs("data-list").OnElements("li")
	// Image resizing stores the selected dimensions directly on the image.
	policy.AllowAttrs("width", "height").OnElements("img")
	// Only videos generated by the editor's YouTube handler are permitted.
	policy.AllowElements("iframe")
	policy.AllowAttrs("class", "width", "height", "frameborder", "allowfullscreen", "title", "loading").OnElements("iframe")
	policy.AllowAttrs("src").Matching(regexp.MustCompile(`^https://www\.youtube-nocookie\.com/embed/[A-Za-z0-9_-]{11}$`)).OnElements("iframe")
	return policy
}
