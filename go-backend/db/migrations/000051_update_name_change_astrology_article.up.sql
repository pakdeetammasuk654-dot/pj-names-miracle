<h2>ก่อนอื่น แยกให้ชัดว่าจะเปลี่ยน “ชื่อตัว” หรือ “ชื่อสกุล”</h2>
<p>สองเรื่องนี้ใช้หลักพิจารณาไม่เหมือนกันทั้งหมด</p>
<ul>
  <li><strong>เปลี่ยนชื่อตัว</strong> เช่น จาก “กมล” เป็น “กมลชนก” นายทะเบียนจะตรวจการสะกดและลักษณะต้องห้ามของชื่อ</li>
  <li><strong>ตั้งชื่อสกุลใหม่</strong> คือการขอจดทะเบียนนามสกุลที่ยังไม่มีผู้จดทะเบียน ไม่ใช่เพียงนำชื่อสกุลของคนอื่นมาใช้</li>
  <li><strong>เปลี่ยนหรือร่วมใช้ชื่อสกุล</strong> เช่น ใช้ชื่อสกุลคู่สมรส บิดา มารดา หรือชื่อสกุลที่เจ้าของอนุญาต ต้องมีหลักฐานตามเหตุแห่งการเปลี่ยนนั้นด้วย</li>
</ul>

<h2>เปลี่ยนชื่อที่อำเภอต้องเตรียมอะไรบ้าง?</h2>
<h3>เอกสารหลักสำหรับการเปลี่ยนชื่อตัว</h3>
<ol>
  <li><strong>บัตรประจำตัวประชาชนตัวจริง</strong></li>
  <li><strong>ทะเบียนบ้านหรือสำเนาทะเบียนบ้าน</strong> แม้หลายสำนักทะเบียนตรวจข้อมูลจากฐานทะเบียนราษฎรได้แล้ว การพกสำเนาไว้ช่วยลดปัญหาเมื่อข้อมูลต้องตรวจเพิ่มเติม</li>
  <li><strong>หนังสือสำคัญแสดงการเปลี่ยนชื่อเดิม แบบ ช.3</strong> หากเคยเปลี่ยนชื่อหรือมีรายการเดิมที่เกี่ยวข้อง</li>
