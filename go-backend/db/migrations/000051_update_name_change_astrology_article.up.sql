  <li><strong>ไม่ซ้ำกับชื่อสกุลพระราชทานหรือชื่อสกุลที่จดทะเบียนไว้แล้ว</strong></li>
  <li>ไม่มีคำหรือความหมายหยาบคาย</li>
  <li>มีพยัญชนะไม่เกิน 10 พยัญชนะ เว้นแต่กรณีใช้ราชทินนามเป็นชื่อสกุล</li>
  <li>ผู้ที่ไม่ได้รับพระราชทานชื่อสกุลไม่ควรใช้ “ณ” นำหน้าชื่อสกุล และมีข้อห้ามเกี่ยวกับนามพระมหานครหรือศัพท์ที่ใช้เป็นพระปรมาภิไธย</li>
