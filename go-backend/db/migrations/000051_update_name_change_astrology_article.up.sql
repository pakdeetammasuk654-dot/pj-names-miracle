<h2>ชื่อแบบไหนที่นายทะเบียนพิจารณาได้?</h2>
<h3>หลักของชื่อตัว</h3>
<p>ตามพระราชบัญญัติชื่อบุคคล ชื่อตัวต้องไม่พ้องหรือมุ่งหมายให้คล้ายกับพระปรมาภิไธย พระนามของพระราชินี หรือราชทินนาม และต้องไม่มีคำหรือความหมายหยาบคาย</p>

<p><strong>เจ้าหน้าที่บังคับว่าชื่อต้องมีความหมายมงคลหรือไม่?</strong> กฎหมายไม่ได้กำหนดว่าทุกชื่อต้องเป็น “ชื่อมงคล” แต่เจ้าหน้าที่ต้องตรวจคำและความหมายว่าไม่ขัดกฎหมาย การเตรียมความหมายที่ชัดเจนและใช้ตัวสะกดมาตรฐานจึงช่วยให้สื่อสารกับเจ้าหน้าที่ได้ง่ายขึ้น และที่สำคัญคือช่วยให้เจ้าของชื่อมั่นใจว่าชื่อนั้นสื่อสิ่งที่ตนตั้งใจจริง</p>

<h3>หลักของชื่อสกุลเข้มกว่า</h3>
<p>ชื่อสกุลที่ขอจดทะเบียนต้องผ่านหลักสำคัญ เช่น</p>
